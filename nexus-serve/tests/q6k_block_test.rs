//! Standalone test for Q6_K dequantization using a known block
//! from the Qwen2.5 Coder 1.5B token_embd.weight, block 0.

use nexus_serve::model::gguf::dequantize_q6_k;

#[test]
fn test_dequantize_q6_k_block_0() {
    let block: [u8; 210] = [
        0xDE, 0x98, 0xB4, 0x90, 0xC1, 0x08, 0x2A, 0x37,
        0xCF, 0xD2, 0x01, 0x17, 0xC7, 0x18, 0xE4, 0x7A,
        0x4B, 0x91, 0x1F, 0xA0, 0x04, 0x00, 0xC8, 0x8A,
        0x9B, 0xAC, 0x1E, 0xE3, 0x05, 0xD6, 0x3C, 0x4D,
        0x1C, 0x99, 0x8A, 0x31, 0x9C, 0x58, 0xA7, 0xB8,
        0x87, 0x0F, 0x80, 0x5D, 0x9A, 0xE9, 0xE0, 0x80,
        0x29, 0x1C, 0x51, 0xF3, 0x9B, 0x5F, 0x16, 0xF1,
        0x06, 0x7E, 0x8A, 0xA0, 0xE6, 0x13, 0xA2, 0x92,
        0xB1, 0x61, 0xBC, 0xEC, 0xBB, 0xC5, 0xD1, 0x37,
        0xFC, 0x2C, 0x92, 0x31, 0x01, 0xF7, 0xF1, 0x94,
        0x9B, 0xC7, 0x77, 0xD1, 0xD0, 0x01, 0x0E, 0x4F,
        0xE1, 0xD3, 0x90, 0x0D, 0xBA, 0x47, 0xA6, 0x42,
        0x38, 0x94, 0x93, 0xF0, 0x4A, 0xAF, 0xC0, 0x17,
        0x93, 0xDD, 0x5C, 0x20, 0xD2, 0x31, 0x49, 0x4E,
        0x59, 0x83, 0xDF, 0xA1, 0x77, 0x51, 0xF9, 0x15,
        0x47, 0xE7, 0x24, 0xCD, 0x92, 0x13, 0x15, 0x36,
        0x98, 0x46, 0x57, 0xE2, 0x08, 0x66, 0x29, 0x6C,
        0x87, 0x24, 0x69, 0x88, 0x9A, 0xD9, 0xAE, 0xAE,
        0x81, 0xAF, 0xAE, 0x44, 0x55, 0x41, 0x25, 0xAA,
        0x98, 0x65, 0x9D, 0x91, 0x98, 0x8E, 0x29, 0x26,
        0xD7, 0xAE, 0x18, 0x79, 0xD9, 0x4E, 0xE3, 0x26,
        0x5A, 0x39, 0xA6, 0xAA, 0x4A, 0xAF, 0x80, 0xD7,
        0xB2, 0x6E, 0x44, 0x64, 0x9E, 0x43, 0x5C, 0x54,
        0xE1, 0x6A, 0x19, 0x95, 0xE9, 0x2D, 0xDE, 0xA7,
        0x47, 0x4E, 0xA7, 0xAC, 0x9B, 0xC5, 0x86, 0x6A,
        0xA1, 0x80, 0xAC, 0xBC, 0xA3, 0x95, 0xAE, 0xB9,
        0xC6, 0x00,
    ];

    let expected_first_10: [f32; 10] = [
        -0.015082597732543945, 0.006703376770019531, 0.016758441925048828, 0.0,
        -0.025975584983825684, 0.006703376770019531, -0.0050275325775146484, -0.020948052406311035,
        0.025975584983825684, -0.025137662887573242,
    ];
    let expected_max_abs: f32 = 0.0468292236328125;

    let mut output = vec![0.0f32; 256];
    dequantize_q6_k(&block, &mut output);

    println!("Output first 10: {:?}", &output[..10]);
    println!("Output max abs: {}", output.iter().map(|v| v.abs()).fold(0.0f32, f32::max));

    for i in 0..10 {
        assert!(
            (output[i] - expected_first_10[i]).abs() < 1e-5,
            "Mismatch at index {}: got {}, expected {}",
            i, output[i], expected_first_10[i]
        );
    }

    let actual_max = output.iter().map(|v| v.abs()).fold(0.0f32, f32::max);
    assert!(
        (actual_max - expected_max_abs).abs() < 1e-4,
        "Max abs mismatch: got {}, expected {}",
        actual_max, expected_max_abs
    );
}
